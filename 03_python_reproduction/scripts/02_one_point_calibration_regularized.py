def theta_batch_from_q(method: str, q):
    import torch

    if method == "Paper":
        return {"b": torch.exp(q[:, 0]), "c": torch.exp(q[:, 1])}
    if method == "M1":
        return {"k": torch.exp(q[:, 0]), "b": torch.exp(q[:, 1])}
    if method == "M2":
        return {"lambda": torch.exp(q[:, 0]), "B": torch.exp(q[:, 1])}
    if method == "M2pro":
        sp = torch.sigmoid(q[:, 2])
        return {
            "lambda": torch.exp(q[:, 0]),
            "B": torch.exp(q[:, 1]),
            "p": 1.2 + (3.0 - 1.2) * sp,
        }

    th = {
        "lambda": torch.exp(q[:, 0]),
        "B": torch.exp(q[:, 1]),
        "a0": q[:, 2],
        "a1": q[:, 3],
        "a2": q[:, 4],
        "a3": q[:, 5],
    }
    if method == "EXP1":
        th["delta"] = -0.8 + 1.6 * torch.sigmoid(q[:, 6])
    elif method == "EXP2":
        th["delta"] = -0.8 + 1.6 * torch.sigmoid(q[:, 6])
        th["gamma"] = 0.6 + 0.8 * torch.sigmoid(q[:, 7])
    elif method == "EXP3":
        th["delta"] = -0.8 + 1.6 * torch.sigmoid(q[:, 6])
        th["tau"] = -1.0 + 2.0 * torch.sigmoid(q[:, 7])
    return th


def basis_batch_grid(method: str, th: dict[str, Any], T):
    import torch

    T = T.view(1, -1)
    if method == "Paper":
        z = torch.clamp(T / (th["c"].view(-1, 1) + 1e-12), -EXP_CLIP, EXP_CLIP)
        return 1.0 / (torch.pow(torch.tensor(2.0, device=T.device), z) + th["b"].view(-1, 1))

    x = torch.clamp((T - TMIN_NORM) / (TMAX_NORM - TMIN_NORM), 0.0, 1.0)
    if method == "M1":
        z = torch.clamp(th["k"].view(-1, 1) * x, -EXP_CLIP, EXP_CLIP)
        return 1.0 / (torch.pow(torch.tensor(2.0, device=T.device), z) + th["b"].view(-1, 1))
    if method == "M2":
        z = torch.clamp(th["lambda"].view(-1, 1) * x * x, -EXP_CLIP, EXP_CLIP)
        return 1.0 / (torch.exp(z) + th["B"].view(-1, 1))
    if method == "M2pro":
        z = torch.clamp(th["lambda"].view(-1, 1) * torch.pow(x, th["p"].view(-1, 1)), -EXP_CLIP, EXP_CLIP)
        return 1.0 / (torch.exp(z) + th["B"].view(-1, 1))

    g = (
        th["a0"].view(-1, 1)
        + th["a1"].view(-1, 1) * x
        + th["a2"].view(-1, 1) * x * x
        + th["a3"].view(-1, 1) * x * x * x
    )
    pbase = EXP_PMIN + (EXP_PMAX - EXP_PMIN) * torch.sigmoid(g)
    if method == "EXP0":
        ptag = pbase
    elif method == "EXP1":
        ptag = pbase + th["delta"].view(-1, 1)
    elif method == "EXP2":
        ptag = th["gamma"].view(-1, 1) * pbase + th["delta"].view(-1, 1)
    else:
        ptag = pbase + th["delta"].view(-1, 1) + th["tau"].view(-1, 1) * (x - 0.5)
    ptag = torch.clamp(ptag, EXP_PMIN, EXP_PMAX)
    z = torch.clamp(th["lambda"].view(-1, 1) * torch.pow(x, ptag), -EXP_CLIP, EXP_CLIP)
    return 1.0 / (torch.exp(z) + th["B"].view(-1, 1))


def basis_batch_row(method: str, th: dict[str, Any], T0):
    import torch

    if method == "Paper":
        z = torch.clamp(T0 / (th["c"] + 1e-12), -EXP_CLIP, EXP_CLIP)
        return 1.0 / (torch.pow(torch.tensor(2.0, device=T0.device), z) + th["b"])

    x = torch.clamp((T0 - TMIN_NORM) / (TMAX_NORM - TMIN_NORM), 0.0, 1.0)
    if method == "M1":
        z = torch.clamp(th["k"] * x, -EXP_CLIP, EXP_CLIP)
        return 1.0 / (torch.pow(torch.tensor(2.0, device=T0.device), z) + th["b"])
    if method == "M2":
        z = torch.clamp(th["lambda"] * x * x, -EXP_CLIP, EXP_CLIP)
        return 1.0 / (torch.exp(z) + th["B"])
    if method == "M2pro":
        z = torch.clamp(th["lambda"] * torch.pow(x, th["p"]), -EXP_CLIP, EXP_CLIP)
        return 1.0 / (torch.exp(z) + th["B"])

    g = th["a0"] + th["a1"] * x + th["a2"] * x * x + th["a3"] * x * x * x
    pbase = EXP_PMIN + (EXP_PMAX - EXP_PMIN) * torch.sigmoid(g)
    if method == "EXP0":
        ptag = pbase
    elif method == "EXP1":
        ptag = pbase + th["delta"]
    elif method == "EXP2":
        ptag = th["gamma"] * pbase + th["delta"]
    else:
        ptag = pbase + th["delta"] + th["tau"] * (x - 0.5)
    ptag = torch.clamp(ptag, EXP_PMIN, EXP_PMAX)
    z = torch.clamp(th["lambda"] * torch.pow(x, ptag), -EXP_CLIP, EXP_CLIP)
    return 1.0 / (torch.exp(z) + th["B"])


def batch_adapt_theta(mod, method: str, ctx: dict[str, Any], reg_df: pd.DataFrame, device) -> tuple[pd.DataFrame, np.ndarray]:
    import torch

    n = len(reg_df)
    q0 = mod.q0_from_theta0(method, ctx["theta0"], device=device).float()
    q = torch.nn.Parameter(q0.view(1, -1).repeat(n, 1))
    opt = torch.optim.Adam([q], lr=float(getattr(mod, "ADAPT_LR", 0.06)))

    alpha_train = float(ctx["hp"]["alpha_train"])
    alpha_theta = float(ctx["hp"]["alpha_theta"])
    alpha_sprior = float(ctx["hp"]["alpha_sprior"])
    alpha_p = float(ctx["hp"].get("alpha_p", 0.0))
    alpha_smooth = float(ctx["hp"].get("alpha_smooth", 0.0))
    mu = torch.tensor(float(ctx["mu_log_s"]), dtype=torch.float32, device=device)
    sig = torch.tensor(float(max(ctx["sig_log_s"], 1e-6)), dtype=torch.float32, device=device)
    T0 = torch.tensor(reg_df["T0"].to_numpy(dtype=np.float32), dtype=torch.float32, device=device)
    y0 = torch.tensor(reg_df["y0"].to_numpy(dtype=np.float32), dtype=torch.float32, device=device)
    train_Ts = [torch.tensor(tg["T"], dtype=torch.float32, device=device) for tg in ctx["train_tags"]]
    train_ys = [torch.tensor(tg["y"], dtype=torch.float32, device=device) for tg in ctx["train_tags"]]

    for _ in range(int(getattr(mod, "ADAPT_ITERS", 80))):
        opt.zero_grad()
        th = theta_batch_from_q(method, q)
        train_sse = torch.zeros(n, dtype=torch.float32, device=device)
        for Ttr, ytr in zip(train_Ts, train_ys):
            b = torch.clamp(basis_batch_grid(method, th, Ttr), 1e-12, 1e12)
            ytr2 = ytr.view(1, -1)
            s_i = torch.sum(b * ytr2, dim=1) / (torch.sum(b * b, dim=1) + 1e-12)
            residual = ytr2 - s_i.view(-1, 1) * b
            train_sse = train_sse + torch.sum(residual * residual, dim=1)

        bas0 = torch.clamp(basis_batch_row(method, th, T0), 1e-12, 1e12)
        s_hat = torch.clamp(y0 / bas0, 1e-12, 1e18)
        loss_vec = (
            alpha_train * train_sse
            + alpha_theta * torch.sum((q - q0.view(1, -1)) * (q - q0.view(1, -1)), dim=1)
            + alpha_sprior * torch.pow((torch.log(s_hat) - mu) / sig, 2.0)
        )
        if method == "M2pro" and alpha_p > 0:
            loss_vec = loss_vec + alpha_p * torch.pow(th["p"] - 2.0, 2.0)
        if method.startswith("EXP") and alpha_smooth > 0:
            xg = torch.linspace(0.0, 1.0, steps=60, device=device).view(1, -1)
            g = (
                th["a0"].view(-1, 1)
                + th["a1"].view(-1, 1) * xg
                + th["a2"].view(-1, 1) * xg * xg
                + th["a3"].view(-1, 1) * xg * xg * xg
            )
            pbase = EXP_PMIN + (EXP_PMAX - EXP_PMIN) * torch.sigmoid(g)
            d2 = pbase[:, 2:] - 2.0 * pbase[:, 1:-1] + pbase[:, :-2]
            loss_vec = loss_vec + alpha_smooth * torch.sum(d2 * d2, dim=1)
        loss = torch.sum(loss_vec)
        if not torch.isfinite(loss).item():
            break
        loss.backward()
        opt.step()

    with torch.no_grad():
        th_final = theta_batch_from_q(method, q)
        bas0 = torch.clamp(basis_batch_row(method, th_final, T0), 1e-12, 1e12)
        s_hat_final = (y0 / bas0).detach().cpu().numpy().astype(float)
        theta_cols = {k: v.detach().cpu().numpy().astype(float) for k, v in th_final.items()}
    return pd.DataFrame(theta_cols), s_hat_final


def summarize_error_rows(rows: list[dict[str, Any]]) -> pd.DataFrame:
    df = pd.DataFrame(rows)
    out = []
    if df.empty:
        return pd.DataFrame()
    for (source_group, batch, epc, reg_label, method), g_all in df.groupby(["source_group", "batch", "EPC", "REG_LABEL", "method"]):
        g = g_all[g_all["status"].astype(str).str.upper() == "ACCEPT"].copy()
        g["MAE"] = pd.to_numeric(g["MAE"], errors="coerce")
        g["RMSE"] = pd.to_numeric(g["RMSE"], errors="coerce")
        g["MaxAE"] = pd.to_numeric(g["MaxAE"], errors="coerce")
        g_valid = g[np.isfinite(g["MAE"])].copy()
        if g_valid.empty:
            best = None
        else:
            best = g_valid.sort_values("MAE").iloc[0]
        out.append(
            {
                "source_group": source_group,
                "batch": batch,
                "EPC": epc,
                "REG_LABEL": reg_label,
                "method": method,
                "beta": "",
                "reg_points_total": int(len(g_all)),
                "reg_points_ACCEPT": int(len(g_valid)),
                "ACCEPT_rate": float(len(g_valid) / max(len(g_all), 1)),
                "MAE_over_ACCEPT_mean": "" if g_valid.empty else float(g_valid["MAE"].mean()),
                "RMSE_over_ACCEPT_mean": "" if g_valid.empty else float(g_valid["RMSE"].mean()),
                "MaxAE_over_ACCEPT_mean": "" if g_valid.empty else float(g_valid["MaxAE"].mean()),
                "best_reg_idx": "" if best is None else int(best["reg_idx"]),
                "best_T0": "" if best is None else float(best["T0"]),
                "best_y0": "" if best is None else float(best["y0"]),
                "best_MAE": "" if best is None else float(best["MAE"]),
                "best_RMSE": "" if best is None else float(best["RMSE"]),
                "best_MedianAE": "" if best is None else float(best["MedianAE"]),
                "best_P95AE": "" if best is None else float(best["P95AE"]),
                "best_MaxAE": "" if best is None else float(best["MaxAE"]),
                "best_Bias": "" if best is None else float(best["Bias"]),
                "best_objective": "" if best is None else float(best["MAE"]),
            }
        )
    return pd.DataFrame(out)


def run_fast_registration_batched(mod, reg_tags: list[dict[str, Any]], method_ctx, raw_loader) -> None:
    import torch

    device = torch.device("cpu")
    reg_rows = []
    for reg_tag in reg_tags:
        tag = str(reg_tag["EPC"]).upper()
        source_group = source_group_for_tag(tag)
        for idx, (T0, y0) in enumerate(zip(reg_tag["T"], reg_tag["y"]), start=1):
            reg_rows.append(
                {
                    "source_group": source_group,
                    "batch": batch_label_for_source(source_group),
                    "EPC": tag,
                    "REG_LABEL": tag,
                    "reg_idx": int(idx),
                    "T0": float(T0),
                    "y0": float(y0),
                    "raw_file": str(TAG_CACHE[tag]["path"]),
                }
            )
    reg_df = pd.DataFrame(reg_rows)

    eval_cache = {}
    for tag in all_validation_tags():
        raw = raw_loader(tag, None, None, None)
        T_raw = np.asarray(raw["T_true"], dtype=np.float64)
        y_raw = np.asarray(raw["y_obs"], dtype=np.float64)
        time_raw = np.asarray(raw["rfid_sec"], dtype=np.float64)
        mask = np.isfinite(T_raw) & np.isfinite(y_raw) & (T_raw >= TEMP_EDGES[0]) & (T_raw <= TEMP_EDGES[-1])
        eval_cache[tag] = {
            "T_true": T_raw[mask],
            "y_obs": y_raw[mask],
            "rfid_sec": time_raw[mask],
            "file": raw.get("file", ""),
        }

    all_errors: list[dict[str, Any]] = []
    all_params: list[dict[str, Any]] = []
    all_bins: list[dict[str, Any]] = []

    for method in METHOD_ORDER:
        ctx = method_ctx[method]
        theta_df, s_hat_arr = batch_adapt_theta(mod, method, ctx, reg_df, device)
        s_train = np.asarray(ctx["s_train"], dtype=np.float64)
        med_s = float(ctx["med_s"])
        mad_s = float(ctx["mad_s"])
        beta = float(ctx["beta"])

        for row_pos, row in reg_df.reset_index(drop=True).iterrows():
            tag = str(row["EPC"])
            raw = eval_cache[tag]
            T_true = raw["T_true"]
            y_obs = raw["y_obs"]
            n_eval = int(len(T_true))
            base = {
                "source_group": row["source_group"],
                "batch": row["batch"],
                "EPC": tag,
                "REG_LABEL": tag,
                "method": method,
                "formula": method_to_formula(method),
                "reg_idx": int(row["reg_idx"]),
                "T0": float(row["T0"]),
                "y0": float(row["y0"]),
                "raw_file": row["raw_file"],
            }
            theta = {col: float(theta_df.iloc[row_pos][col]) for col in theta_df.columns}
            s_hat = float(s_hat_arr[row_pos])
            param_row = dict(base)
            param_row.update({"s_hat": s_hat})
            param_row.update(theta)

            def add_reject(reason: str, zS: Any = "", zY: Any = "") -> None:
                err_row = dict(base)
                err_row.update(
                    {
                        "status": "REJECT",
                        "reason": reason,
                        "zS": zS,
                        "zY": zY,
                        "nEvalPts": n_eval,
                        "nPredValid": 0,
                        "validPredRatio": 0.0,
                        "MAE": "",
                        "RMSE": "",
                        "MedianAE": "",
                        "P95AE": "",
                        "MaxAE": "",
                        "Bias": "",
                    }
                )
                param_row.update({"status": "REJECT", "reason": reason, "zS": zS, "zY": zY})
                all_errors.append(err_row)
                all_params.append(dict(param_row))

            if n_eval == 0:
                add_reject("no_raw_eval_points")
                continue
            if (not np.isfinite(s_hat)) or s_hat <= 0:
                add_reject("invalid_s")
                continue

            zS = mod.z_robust_scalar(s_hat, med_s, mad_s)
            bas0 = mod.method_basis_np(method, ctx["theta0"], float(row["T0"]))
            if (not np.isfinite(bas0)) or bas0 <= 0 or s_train.size < 2:
                add_reject("basis0_invalid", zS=zS)
                continue
            y_train0 = s_train * bas0
            zY = mod.z_robust_scalar(float(row["y0"]), float(np.median(y_train0)), mod.robust_mad(y_train0))
            if abs(zS) > float(ctx["z_thresh_s"]) or abs(zY) > float(ctx["z_thresh_y"]):
                add_reject("z_outlier", zS=zS, zY=zY)
                continue

            T_hat = mod.method_invert_np(method, theta, s_hat, y_obs)
            metrics = mod.compute_error_metrics(T_hat, T_true)
            if metrics["nPredValid"] == 0:
                add_reject("invert_fail", zS=zS, zY=zY)
                continue

            err_row = dict(base)
            err_row.update({"status": "ACCEPT", "reason": "", "zS": zS, "zY": zY})
            err_row.update(metrics)
            all_errors.append(err_row)
            param_row.update({"status": "ACCEPT", "reason": "", "zS": zS, "zY": zY})
            all_params.append(dict(param_row))
            mod.add_tempbin_rows(all_bins, {**base, "status": "ACCEPT"}, T_hat, T_true)

    errors_df = pd.DataFrame(all_errors)
    params_df = pd.DataFrame(all_params)
    bins_df = pd.DataFrame(all_bins)

    for info in BATCHES:
        group_dir = OUTPUT_RESULT_ROOT / info["source_group"]
        group_dir.mkdir(parents=True, exist_ok=True)
        g_errors = errors_df[errors_df["source_group"] == info["source_group"]].copy()
        g_params = params_df[params_df["source_group"] == info["source_group"]].copy()
        g_bins = bins_df[bins_df["source_group"] == info["source_group"]].copy()
        g_summary = summarize_error_rows(g_errors.to_dict("records"))
        g_overall = mod.build_overall_summary(g_errors.to_dict("records"))
        g_errors.to_csv(group_dir / "all_tags_errors_points.csv", index=False, encoding="utf-8-sig")
        g_summary.to_csv(group_dir / "all_tags_errors_summary.csv", index=False, encoding="utf-8-sig")
        g_bins.to_csv(group_dir / "all_tags_errors_by_tempbin.csv", index=False, encoding="utf-8-sig")
        g_params.to_csv(group_dir / "all_tags_params_points.csv", index=False, encoding="utf-8-sig")
        mod.write_rows(str(group_dir / "all_methods_overall_summary.csv"), g_overall)
        mod.write_rows(str(group_dir / "all_methods_overall_summary_cn.csv"), mod.build_overall_summary_cn(g_overall))
        pd.DataFrame().to_csv(group_dir / "raw_point_filter_report.csv", index=False, encoding="utf-8-sig")

    combined_dir = OUTPUT_RESULT_ROOT / "C201_C301_C350_combined"
    combined_dir.mkdir(parents=True, exist_ok=True)
    summary_df = summarize_error_rows(errors_df.to_dict("records"))
    errors_df.to_csv(combined_dir / "all_tags_errors_points.csv", index=False, encoding="utf-8-sig")
    summary_df.to_csv(combined_dir / "all_tags_errors_summary.csv", index=False, encoding="utf-8-sig")
    bins_df.to_csv(combined_dir / "all_tags_errors_by_tempbin.csv", index=False, encoding="utf-8-sig")
    params_df.to_csv(combined_dir / "all_tags_params_points.csv", index=False, encoding="utf-8-sig")
    overall = mod.build_overall_summary(errors_df.to_dict("records"))
    mod.write_rows(str(combined_dir / "all_methods_overall_summary.csv"), overall)
    mod.write_rows(str(combined_dir / "all_methods_overall_summary_cn.csv"), mod.build_overall_summary_cn(overall))
    pd.DataFrame().to_csv(combined_dir / "raw_point_filter_report.csv", index=False, encoding="utf-8-sig")

    manifest = {
        "created_by": Path(__file__).name,
        "source_groups": [x["source_group"] for x in BATCHES],
        "output_group": combined_dir.name,
        "offline_model_source": "outputs/offline_training generated by train_all_models.py",
        "online_adaptation_rerun": True,
    }
    (combined_dir / "merge_manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")


