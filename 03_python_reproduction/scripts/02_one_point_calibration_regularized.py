def natural_key(text: str) -> tuple:
    import re

    parts = re.split(r"(\d+)", str(text))
    return tuple(int(part) if part.isdigit() else part for part in parts)


def build_sliding_window_cache(helper, tags: list[str]) -> dict[str, dict[str, Any]]:
    cache: dict[str, dict[str, Any]] = {}
    query_secs = []
    missing = []

    for tag in tags:
        if tag in cache:
            continue
        path = DISCHARGE_DIR / f"{tag}.csv"
        if not path.exists():
            missing.append(tag)
            continue
        _thermo, sliding = helper.load_tag_csv(path)
        sliding = sliding.sort_values("event_sec").reset_index(drop=True)
        cache[tag] = {"path": path, "sliding": sliding}
        if len(sliding):
            query_secs.append(sliding["event_sec"].to_numpy(dtype=float))

    if missing:
        raise FileNotFoundError(f"Missing discharge CSV for tags: {missing[:10]}")
    if not query_secs:
        raise RuntimeError("No valid sliding-window observations were loaded.")

    cache["_query_sec"] = {"values": np.concatenate(query_secs)}
    return cache


