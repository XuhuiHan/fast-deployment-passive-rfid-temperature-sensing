def weighted_mean(values: pd.Series, weights: pd.Series) -> float:
    v = pd.to_numeric(values, errors="coerce").to_numpy(dtype=float)
    w = pd.to_numeric(weights, errors="coerce").to_numpy(dtype=float)
    ok = np.isfinite(v) & np.isfinite(w) & (w > 0)
    if not np.any(ok):
        return float("nan")
    return float(np.sum(v[ok] * w[ok]) / np.sum(w[ok]))


def sample_std(values: pd.Series) -> float:
    v = pd.to_numeric(values, errors="coerce").to_numpy(dtype=float)
    v = v[np.isfinite(v)]
    if len(v) <= 1:
        return 0.0 if len(v) == 1 else float("nan")
    return float(np.std(v, ddof=1))


def assign_temp_bin(values: pd.Series) -> pd.Series:
    x = pd.to_numeric(values, errors="coerce")
    labels = pd.cut(x, bins=TEMP_EDGES, labels=TEMP_LABELS, right=False, include_lowest=True)
    labels = labels.astype(object)
    labels.loc[x == TEMP_EDGES[-1]] = TEMP_LABELS[-1]
    return labels


def empirical_cdf(values: pd.Series | np.ndarray) -> pd.DataFrame:
    arr = np.asarray(values, dtype=float)
    arr = np.sort(arr[np.isfinite(arr)])
    if len(arr) == 0:
        return pd.DataFrame({"error_C": [], "cdf": []})
    return pd.DataFrame({"error_C": arr, "cdf": np.arange(1, len(arr) + 1) / len(arr)})


def fit_mean_parameter_thermotag(
    helper,
    train_tags: list[dict[str, Any]],
) -> tuple[float, float, float, pd.DataFrame]:
    expected_epcs = {f"C{i}" for i in range(250, 283)}
    actual_epcs = {str(tag["EPC"]).upper() for tag in train_tags}
    if len(train_tags) != EXPECTED_LEARNING_TAGS or actual_epcs != expected_epcs:
        raise RuntimeError(
            "ThermoTag baseline requires exactly the 33 learning tags C250-C282; "
            f"received {len(train_tags)} tags: {sorted(actual_epcs, key=natural_key)}"
        )

    fit_rows: list[dict[str, Any]] = []
    for tag in sorted(train_tags, key=lambda item: natural_key(str(item["EPC"]))):
        epc = str(tag["EPC"]).upper()
        temperature = np.asarray(tag["T"], dtype=float)
        persistence_time = np.asarray(tag["y"], dtype=float)
        if temperature.shape != persistence_time.shape:
            raise RuntimeError(f"Mismatched temperature/persistence arrays for {epc}.")
        fit = helper.fit_abc(temperature, persistence_time)
        fit_rows.append(
            {
                "EPC": epc,
                "a": float(fit["a"]),
                "b": float(fit["b"]),
                "c": float(fit["c"]),
                "curve_rmse_s": float(fit["curve_rmse_s"]),
                "curve_r2": float(fit["curve_r2"]),
                "n_curve_points": int(fit["n_curve_points"]),
                "temperature_min_C": float(np.min(temperature)),
                "temperature_max_C": float(np.max(temperature)),
            }
        )

    learning_fits = pd.DataFrame(fit_rows)
    means = learning_fits[["a", "b", "c"]].mean(axis=0)
    if not np.all(np.isfinite(means.to_numpy(dtype=float))):
        raise RuntimeError("Non-finite mean ThermoTag parameters from the 33 learning tags.")
    learning_fits.to_csv(
        OUTPUT_RESULT_ROOT / "thermotag_mean_parameter_learning_tag_fits.csv",
        index=False,
        encoding="utf-8-sig",
    )
    return float(means["a"]), float(means["b"]), float(means["c"]), learning_fits


def build_thermotag_mean_parameter_baseline(
    helper,
    train_tags: list[dict[str, Any]],
    temp_sec_eval: np.ndarray,
    temp_val_eval: np.ndarray,
):
    a, b, c, learning_fits = fit_mean_parameter_thermotag(helper, train_tags)
    point_frames = []
    failures = []

    for tag in all_validation_tags():
        source_group = source_group_for_tag(tag)
        obs = TAG_CACHE[tag]["sliding"].copy()
        obs["true_temp_C"] = helper.interpolate_temperature(
            obs["event_sec"].to_numpy(dtype=float),
            temp_sec_eval,
            temp_val_eval,
        )
        obs = obs[
            np.isfinite(obs["true_temp_C"])
            & (obs["true_temp_C"] >= TEMP_EDGES[0])
            & (obs["true_temp_C"] <= TEMP_EDGES[-1])
            & np.isfinite(obs["persistence_time_s"])
            & (obs["persistence_time_s"] > 0)
            & (obs["persistence_time_s"] <= helper.EVAL_TIME_MAX_S)
        ].copy()
        if obs.empty:
            failures.append({"tag": tag, "source_group": source_group, "error": "no valid evaluation points"})
            continue
        pred = helper.inverse_temperature(obs["persistence_time_s"].to_numpy(dtype=float), a, b, c)
        ok = np.isfinite(pred)
        obs = obs.loc[ok].copy()
        pred = pred[ok]
        if obs.empty:
            failures.append({"tag": tag, "source_group": source_group, "error": "no valid inverse-temperature predictions"})
            continue
        obs["tag"] = tag
        obs["source_group"] = source_group
        obs["batch"] = batch_label_for_source(source_group)
        obs["method"] = PAPER_LABEL_BASELINE
        obs["rfid_sec"] = obs["event_sec"].to_numpy(dtype=float)
        obs["fused_time_s"] = obs["persistence_time_s"].to_numpy(dtype=float)
        obs["pred_temp_C"] = pred
        obs["signed_error_C"] = obs["pred_temp_C"] - obs["true_temp_C"]
        obs["abs_error_C"] = np.abs(obs["signed_error_C"])
        obs["temp_bin"] = assign_temp_bin(obs["true_temp_C"])
        point_frames.append(
            obs[
                [
                    "source_group",
                    "batch",
                    "tag",
                    "rfid_sec",
                    "true_temp_C",
                    "fused_time_s",
                    "pred_temp_C",
                    "signed_error_C",
                    "abs_error_C",
                    "method",
                    "temp_bin",
                ]
            ]
        )

    points = pd.concat(point_frames, ignore_index=True) if point_frames else pd.DataFrame()
    points.to_csv(OUTPUT_RESULT_ROOT / "thermotag_mean_parameter_point_errors.csv", index=False, encoding="utf-8-sig")

    per_tag_rows = []
    for (source_group, batch, tag), d in points.groupby(["source_group", "batch", "tag"]):
        err = d["signed_error_C"].to_numpy(dtype=float)
        ae = np.abs(err)
        per_tag_rows.append(
            {
                "source_group": source_group,
                "batch": batch,
                "tag": tag,
                "n_points": int(len(d)),
                "mean_error_C": float(np.mean(ae)),
                "rmse_error_C": float(np.sqrt(np.mean(err * err))),
                "median_error_C": float(np.median(ae)),
                "p95_error_C": float(np.percentile(ae, 95)),
                "max_error_C": float(np.max(ae)),
                "bias_C": float(np.mean(err)),
            }
        )
    per_tag = pd.DataFrame(per_tag_rows)
    per_tag.to_csv(OUTPUT_RESULT_ROOT / "thermotag_mean_parameter_per_tag_summary.csv", index=False, encoding="utf-8-sig")

    temp_rows = []
    for label in TEMP_LABELS:
        d = points[points["temp_bin"].astype(str) == label]
        err = d["signed_error_C"].to_numpy(dtype=float) if len(d) else np.array([])
        ae = np.abs(err)
        temp_rows.append(
            {
                "method": PAPER_LABEL_BASELINE,
                "temp_bin": label,
                "n_points": int(len(d)),
                "n_tags": int(d["tag"].nunique()) if len(d) else 0,
                "mean_error_C": float(np.mean(ae)) if len(ae) else float("nan"),
                "std_error_C": float(np.std(ae, ddof=1)) if len(ae) > 1 else (0.0 if len(ae) == 1 else float("nan")),
                "rmse_error_C": float(np.sqrt(np.mean(err * err))) if len(err) else float("nan"),
            }
        )
    tempbin = pd.DataFrame(temp_rows)
    tempbin.to_csv(OUTPUT_RESULT_ROOT / "thermotag_mean_parameter_tempbin_summary.csv", index=False, encoding="utf-8-sig")

    meta = {
        "learning_tag_count": int(len(learning_fits)),
        "learning_tags": learning_fits["EPC"].tolist(),
        "mean_a": a,
        "mean_b": b,
        "mean_c": c,
        "parameter_aggregation": "Arithmetic mean of parameters fitted separately to the complete multi-temperature data of each learning tag.",
        "individual_fit_file": "thermotag_mean_parameter_learning_tag_fits.csv",
        "mean_learning_fit_R2": float(learning_fits["curve_r2"].mean()),
        "minimum_learning_fit_R2": float(learning_fits["curve_r2"].min()),
        "baseline_definition": "ThermoTag model formed by averaging the separately fitted a, b, and c parameters of learning tags C250-C282 and applying the fixed shared model to all validation tags.",
        "failures": failures,
    }
    (OUTPUT_RESULT_ROOT / "thermotag_mean_parameter_model_info.json").write_text(
        json.dumps(meta, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    return points, per_tag, tempbin


