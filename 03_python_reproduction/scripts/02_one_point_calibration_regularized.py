def fast_exp_ptag_vec(theta: dict[str, float], method: str, x: np.ndarray) -> np.ndarray:
    x = np.asarray(x, dtype=float)
    g = (
        float(theta["a0"])
        + float(theta["a1"]) * x
        + float(theta["a2"]) * x * x
        + float(theta["a3"]) * x * x * x
    )
    pbase = EXP_PMIN + (EXP_PMAX - EXP_PMIN) / (1.0 + np.exp(-np.clip(g, -60.0, 60.0)))
    delta = float(theta.get("delta", 0.0))
    gamma = float(theta.get("gamma", 1.0))
    tau = float(theta.get("tau", 0.0))
    if method == "EXP0":
        ptag = pbase
    elif method == "EXP1":
        ptag = pbase + delta
    elif method == "EXP2":
        ptag = gamma * pbase + delta
    elif method == "EXP3":
        ptag = pbase + delta + tau * (x - 0.5)
    else:
        ptag = pbase
    return np.clip(ptag, EXP_PMIN, EXP_PMAX)


def fast_invert_exp(theta: dict[str, float], method: str, s: float, yobs: np.ndarray) -> np.ndarray:
    y = np.asarray(yobs, dtype=float)
    out = np.full_like(y, np.nan, dtype=float)
    if s <= 0:
        return out
    lam = float(theta["lambda"])
    B = float(theta["B"])
    if lam <= 0 or B <= 0:
        return out

    ptag = fast_exp_ptag_vec(theta, method, INVERSE_X_GRID)
    y_grid = s / (np.exp(np.clip(lam * (INVERSE_X_GRID ** ptag), -EXP_CLIP, EXP_CLIP)) + B)
    ok_grid = np.isfinite(y_grid)
    if ok_grid.sum() < 2:
        return out

    y_axis = y_grid[ok_grid][::-1]
    t_axis = INVERSE_T_GRID[ok_grid][::-1]
    keep = np.r_[True, np.diff(y_axis) > 1e-12]
    y_axis = y_axis[keep]
    t_axis = t_axis[keep]
    if len(y_axis) < 2:
        return out

    ok = np.isfinite(y) & (y > 0) & (y >= y_axis[0]) & (y <= y_axis[-1])
    out[ok] = np.interp(y[ok], y_axis, t_axis)
    return out


